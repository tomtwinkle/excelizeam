func saveGenerated(path string, content []byte) error {
	formatted, err := format.Source(content)
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	if *checkOutput {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("%s is stale; run go generate ./excelizeutil", path)
		}
		return nil
	}
	return os.WriteFile(path, formatted, 0o644)
}

func expressionText(expr ast.Expr) string {
	var b bytes.Buffer
	_ = format.Node(&b, token.NewFileSet(), expr)
	return b.String()
}

func initializer(file *ast.File, name string) ast.Expr {
	var result ast.Expr
	ast.Inspect(file, func(n ast.Node) bool {
		if result != nil {
			return false
		}
		switch node := n.(type) {
		case *ast.ValueSpec:
			for i, id := range node.Names {
				if id.Name == name && i < len(node.Values) {
					result = node.Values[i]
				}
			}
		case *ast.AssignStmt:
			for i, lhs := range node.Lhs {
				if id, ok := lhs.(*ast.Ident); ok && id.Name == name && i < len(node.Rhs) {
					result = node.Rhs[i]
				}
			}
		}
		return true
	})
	return result
}

func stringLiteral(expr ast.Expr) (string, error) {
	v, ok := expr.(*ast.BasicLit)
	if !ok || v.Kind != token.STRING {
		return "", fmt.Errorf("expected string literal: %s", expressionText(expr))
	}
	return strconv.Unquote(v.Value)
}

func stringSwitchValues(file *ast.File, tag string) ([]string, error) {
	var values []string
	var failure error
	ast.Inspect(file, func(n ast.Node) bool {
		sw, ok := n.(*ast.SwitchStmt)
		if !ok || sw.Tag == nil || !strings.HasSuffix(expressionText(sw.Tag), tag) {
			return true
		}
		for _, statement := range sw.Body.List {
			c := statement.(*ast.CaseClause)
			for _, expr := range c.List {
				value, err := stringLiteral(expr)
				if err != nil {
					failure = err
					return false
				}
				values = appendUnique(values, value)
			}
		}
		return false
	})
	if failure != nil {
		return nil, failure
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("cannot locate string switch %s", tag)
	}
	return values, nil
}

func appendUnique(values []string, value string) []string {
	for _, existing := range values {
		if existing == value {
			return values
		}
	}
	return append(values, value)
}

// Alignment has no validation table in Excelize's implementation. Its documented
// choices live in NewStyle's AST comment; general/bottom are OOXML defaults that
// older Excelize documentation omits.
func alignmentOptions(file *ast.File, axis string) ([]string, error) {
	for _, group := range file.Comments {
		lines := strings.Split(group.Text(), "\n")
		for i, line := range lines {
			if !strings.Contains(line, axis+" alignment") {
				continue
			}
			var values []string
			for _, row := range lines[i+1:] {
				text := strings.TrimSpace(row)
				if len(values) > 0 && text == "" {
					break
				}
				if text == "" || text == "Style" || strings.HasPrefix(text, "--") {
					continue
				}
				if strings.ContainsAny(text, " :|'().,\t") {
					continue
				}
				if _, err := enumIdentifier(text); err == nil {
					values = appendUnique(values, text)
				}
			}
			if len(values) > 0 {
				return values, nil
			}
		}
	}
	return nil, fmt.Errorf("cannot locate documented %s alignment choices", axis)
}

func writeStringEnum(out *bytes.Buffer, name string, values []string) error {
	fmt.Fprintf(out, "type %s string\n\nconst (\n", name)
	seen := map[string]bool{}
	for _, value := range values {
		suffix := "Unset"
		var err error
		if value != "" {
			suffix, err = enumIdentifier(strings.ReplaceAll(value, "-", "_"))
		}
		if err != nil {
			return err
		}
		if seen[suffix] {
			return fmt.Errorf("duplicate %s constant %s", name, suffix)
		}
		seen[suffix] = true
		fmt.Fprintf(out, "%s%s %s = %q\n", name, suffix, name, value)
	}
	fmt.Fprintln(out, ")")
	fmt.Fprintf(out, "\nfunc %sValues() []%s { return []%s{", name, name, name)
	for _, value := range values {
		fmt.Fprintf(out, "%q,", value)
	}
	out.WriteString("} }\n\n")
	return nil
}

func additionalEnums(dir string, styles *ast.File, specs []enumSpec) ([]byte, []byte, error) {
	var public bytes.Buffer
	public.WriteString("// Code generated by go generate ./excelizeutil; DO NOT EDIT.\n\npackage excelizestyle\n\nimport \"github.com/xuri/excelize/v2\"\n\n")
	for _, spec := range specs {
		values, err := findEnumValues(styles, spec)
		if err != nil {
			return nil, nil, err
		}
		spec.typeName = strings.ToUpper(spec.typeName[:1]) + spec.typeName[1:]
		spec.constantPrefix = spec.typeName
		if err := writeEnum(&public, spec, values); err != nil {
			return nil, nil, err
		}
	}
	positions, err := stringSwitchValues(styles, "v.Type")
	if expr := initializer(styles, "styleBorderTypes"); expr != nil {
		positions, err = stringValues(expr, "styleBorderTypes")
	}
	if err != nil {
		return nil, nil, err
	}
	fillTypes, err := stringSwitchValues(styles, ".Fill.Type")
	if err != nil {
		return nil, nil, err
	}
	horizontal, err := alignmentOptions(styles, "horizontal")
	if err != nil {
		return nil, nil, err
	}
	vertical, err := alignmentOptions(styles, "vertical")
	if err != nil {
		return nil, nil, err
	}
	horizontal = appendUnique(horizontal, "general")
	vertical = appendUnique(vertical, "bottom")
	underlineExpr := initializer(styles, "fontUnderlineType")
	underline := []string{}
	template, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, "templates.go"), nil, 0)
	if err != nil {
		return nil, nil, err
	}
	if expr := initializer(template, "supportedUnderlineTypes"); expr != nil {
		underline, err = stringValues(expr, "supportedUnderlineTypes")
	} else if literal, ok := underlineExpr.(*ast.CompositeLit); ok {
		for _, e := range literal.Elts {
			value, e := stringLiteral(e.(*ast.KeyValueExpr).Key)
			if e != nil {
				return nil, nil, e
			}
			underline = append(underline, value)
		}
	} else {
		return nil, nil, fmt.Errorf("cannot locate underline choices")
	}
	if err != nil {
		return nil, nil, err
	}
	// An empty underline/fill represents an unset value and must remain expressible.
	fillTypes = appendUnique(fillTypes, "")
	underline = appendUnique(underline, "")
	vertAlign := []string{"baseline", "superscript", "subscript"}
	ast.Inspect(styles, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) < 2 || !strings.HasSuffix(expressionText(call.Args[1]), ".VertAlign") {
			return true
		}
		if _, ok := call.Args[0].(*ast.CompositeLit); ok {
			values, e := stringValues(call.Args[0], "VertAlign")
			if e == nil {
				vertAlign = values
			}
		}
		return true
	})
	for _, spec := range []struct {
		name   string
		values []string
	}{
		{"BorderPosition", positions}, {"FillType", fillTypes},
		{"AlignmentHorizontal", horizontal}, {"AlignmentVertical", vertical},
		{"FontUnderline", underline}, {"FontVerticalAlign", vertAlign},
	} {
		if err := writeStringEnum(&public, spec.name, spec.values); err != nil {
			return nil, nil, err
		}
	}
	public.WriteString("type AlignmentReadingOrder uint64\nconst (AlignmentReadingOrderContext AlignmentReadingOrder = iota; AlignmentReadingOrderLeftToRight; AlignmentReadingOrderRightToLeft)\n\n")
	numberSource := styles
	if initializer(styles, "builtInNumFmt") == nil {
		numberSource, err = parser.ParseFile(token.NewFileSet(), filepath.Join(dir, "numfmt.go"), nil, 0)
		if err != nil {
			return nil, nil, err
		}
	}
	if err := numberAndLanguageEnums(&public, numberSource); err != nil {
		return nil, nil, err
	}
	if err := fieldEnums(&public, dir); err != nil {
		return nil, nil, err
	}
	if err := colorEnums(&public, template); err != nil {
		return nil, nil, err
	}
	if err := typedDefinitions(&public, dir); err != nil {
		return nil, nil, err
	}
	presets, err := gradientPresets(styles)
	if err != nil {
		return nil, nil, err
	}
	fmt.Fprintln(&public, "type GradientShading int\nconst (")
	for i, preset := range presets {
		kind := preset.kind
		if kind == "" {
			kind = "linear"
		}
		fmt.Fprintf(&public, "// GradientShadingPreset%d selects preset %d: %s gradient, degree %g, path bounds (left %g, right %g, top %g, bottom %g), and stop positions [%s].\n//\n// See %s\n", i, i, kind, preset.degree, preset.left, preset.right, preset.top, preset.bottom, numbers(preset.stops), officialStyleDocs)
		fmt.Fprintf(&public, "GradientShadingPreset%d GradientShading = %d\n", i, i)
	}
	fmt.Fprintf(&public, "GradientShadingCount GradientShading = %d\n)\n", len(presets))
	var geometry bytes.Buffer
	fmt.Fprintln(&geometry, "func gradientGeometries() []gradientGeometry { return []gradientGeometry{")
	for _, preset := range presets {
		fmt.Fprintf(&geometry, "{typeName:%q,degree:%g,left:%g,right:%g,top:%g,bottom:%g,positions:[]float64{%s}},\n", preset.kind, preset.degree, preset.left, preset.right, preset.top, preset.bottom, numbers(preset.stops))
	}
	fmt.Fprintln(&geometry, "} }")
	return public.Bytes(), geometry.Bytes(), nil
}

func numberAndLanguageEnums(out *bytes.Buffer, styles *ast.File) error {
	values := map[int]string{}
	allIDs := map[int]bool{}
	for _, name := range []string{"builtInNumFmt", "currencyNumFmt"} {
		formats, ok := initializer(styles, name).(*ast.CompositeLit)
		if !ok {
			return fmt.Errorf("cannot locate %s", name)
		}
		for _, item := range formats.Elts {
			kv, ok := item.(*ast.KeyValueExpr)
			if !ok {
				return fmt.Errorf("unexpected number format entry")
			}
			id, err := strconv.Atoi(expressionText(kv.Key))
			if err != nil {
				return err
			}
			code, err := stringLiteral(kv.Value)
			if err != nil {
				return err
			}
			values[id] = code
			allIDs[id] = true
		}
	}
	languages, ok := initializer(styles, "langNumFmt").(*ast.CompositeLit)
	if !ok {
		return fmt.Errorf("cannot locate langNumFmt")
	}
	languageFormats := map[string]map[int]string{}
	for _, item := range languages.Elts {
		kv := item.(*ast.KeyValueExpr)
		code, err := stringLiteral(kv.Key)
		if err != nil {
			return err
		}
		formats, ok := kv.Value.(*ast.CompositeLit)
		if !ok {
			return fmt.Errorf("unexpected language formats")
		}
		languageFormats[code] = map[int]string{}
		for _, item := range formats.Elts {
			kv := item.(*ast.KeyValueExpr)
			id, err := strconv.Atoi(expressionText(kv.Key))
			if err != nil {
				return err
			}
			value, err := stringLiteral(kv.Value)
			if err != nil {
				return err
			}
			languageFormats[code][id] = value
			allIDs[id] = true
		}
	}
	ids := []int{}
	for id := range allIDs {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	fmt.Fprintln(out, "type NumberFormat int\nconst (")
	for _, id := range ids {
		fmt.Fprintf(out, "NumberFormatID%d NumberFormat = %d\n", id, id)
	}
	fmt.Fprintln(out, ")\n\nfunc (value NumberFormat) Code() (string,bool) { switch value {")
	for _, id := range ids {
		if code, ok := values[id]; ok {
			fmt.Fprintf(out, "case NumberFormatID%d: return %q,true\n", id, code)
		}
	}
	out.WriteString("default:return \"\",false\n} }\n\n")
	var codes []string
	for code := range languageFormats {
		codes = append(codes, code)
	}
	sort.Strings(codes)
	if err := writeStringEnum(out, "StyleLanguage", codes); err != nil {
		return err
	}
	fmt.Fprintln(out, "func (value NumberFormat) CodeForLanguage(language StyleLanguage) (string, bool) { switch language {")
	for _, code := range codes {
		fmt.Fprintf(out, "case %q: switch value {\n", code)
		for _, id := range ids {
			if value, ok := languageFormats[code][id]; ok {
				fmt.Fprintf(out, "case NumberFormatID%d: return %q,true\n", id, value)
			}
		}
		fmt.Fprintln(out, "}")
	}
	fmt.Fprintln(out, "}; return value.Code()\n}")
	return nil
}

func fieldEnums(out *bytes.Buffer, dir string) error {
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, "xmlStyles.go"), nil, 0)
	if err != nil {
		return err
	}
	wanted := map[string]bool{"Style": true, "Border": true, "Fill": true, "Font": true, "Alignment": true, "Protection": true}
	found := map[string]bool{}
	for _, decl := range file.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, s := range group.Specs {
			spec, ok := s.(*ast.TypeSpec)
			if !ok || !wanted[spec.Name.Name] {
				continue
			}
			structure, ok := spec.Type.(*ast.StructType)
			if !ok {
				return fmt.Errorf("%s is no longer a struct", spec.Name.Name)
			}
			var fields []string
			for _, field := range structure.Fields.List {
				for _, name := range field.Names {
					if name.IsExported() {
						fields = append(fields, name.Name)
					}
				}
			}
			if err := writeStringEnum(out, spec.Name.Name+"Field", fields); err != nil {
				return err
			}
			found[spec.Name.Name] = true
		}
	}
	if len(found) != len(wanted) {
		return fmt.Errorf("one or more public Style types are missing")
	}
	return nil
}

type gradientPreset struct {
	kind                             string
	degree, left, right, top, bottom float64
	stops                            []float64
}

func numbers(values []float64) string {
	var parts []string
	for _, v := range values {
		parts = append(parts, strconv.FormatFloat(v, 'g', -1, 64))
	}
	return strings.Join(parts, ",")
}
func numeric(expr ast.Expr) (float64, error) { return strconv.ParseFloat(expressionText(expr), 64) }
func gradientPresets(styles *ast.File) ([]gradientPreset, error) {
	if expr := initializer(styles, "styleFillVariants"); expr != nil {
		fn, ok := expr.(*ast.FuncLit)
		if !ok {
			call, called := expr.(*ast.CallExpr)
			if called {
				fn, ok = call.Fun.(*ast.FuncLit)
			}
		}
		if !ok {
			return nil, fmt.Errorf("unexpected styleFillVariants initializer")
		}
		var literals *ast.CompositeLit
		for _, stmt := range fn.Body.List {
			if ret, ok := stmt.(*ast.ReturnStmt); ok && len(ret.Results) == 1 {
				literals, _ = ret.Results[0].(*ast.CompositeLit)
			}
		}
		if literals == nil {
			return nil, fmt.Errorf("missing gradient return literal")
		}
		var values []gradientPreset
		for _, expr := range literals.Elts {
			literal, ok := expr.(*ast.CompositeLit)
			if !ok {
				return nil, fmt.Errorf("unexpected gradient preset")
			}
			p := gradientPreset{}
			for _, item := range literal.Elts {
				kv, ok := item.(*ast.KeyValueExpr)
				if !ok {
					return nil, fmt.Errorf("unexpected gradient field")
				}
				name := expressionText(kv.Key)
				switch name {
				case "Type":
					v, err := stringLiteral(kv.Value)
					if err != nil {
						return nil, err
					}
					p.kind = v
				case "Stop":
					stops, ok := kv.Value.(*ast.CompositeLit)
					if !ok {
						return nil, fmt.Errorf("unexpected gradient stops")
					}
					for _, expr := range stops.Elts {
						stop, ok := expr.(*ast.CompositeLit)
						if !ok {
							return nil, fmt.Errorf("unexpected gradient stop")
						}
						position := float64(0)
						for _, item := range stop.Elts {
							kv := item.(*ast.KeyValueExpr)
							if expressionText(kv.Key) != "Position" {
								return nil, fmt.Errorf("unsupported gradient stop field")
							}
							var err error
							position, err = numeric(kv.Value)
							if err != nil {
								return nil, err
							}
						}
						p.stops = append(p.stops, position)
					}
				default:
					if err := setGeometry(&p, name, kv.Value); err != nil {
						return nil, err
					}
				}
			}
			if len(p.stops) < 2 || len(p.stops) > 3 {
				return nil, fmt.Errorf("gradient stop count is not representable by the two-color API")
			}
			values = append(values, p)
		}
		return values, nil
	}
	// Excelize v2.6 builds presets with a switch and a degree lookup slice.
	twoColors, indexedPositions := false, false
	ast.Inspect(styles, func(n ast.Node) bool {
		if node, ok := n.(*ast.IfStmt); ok && expressionText(node.Cond) == "len(style.Fill.Color) != 2" {
			twoColors = true
		}
		if node, ok := n.(*ast.AssignStmt); ok && len(node.Lhs) == 1 && len(node.Rhs) == 1 && expressionText(node.Lhs[0]) == "stop.Position" && expressionText(node.Rhs[0]) == "float64(index)" {
			indexedPositions = true
		}
		return true
	})
	if !twoColors || !indexedPositions {
		return nil, fmt.Errorf("unsupported legacy gradient stop construction")
	}
	variants, ok := initializer(styles, "variants").(*ast.CompositeLit)
	if !ok {
		return nil, fmt.Errorf("cannot locate legacy gradient variants")
	}
	var sw *ast.SwitchStmt
	ast.Inspect(styles, func(n ast.Node) bool {
		if v, ok := n.(*ast.SwitchStmt); ok && v.Tag != nil && strings.HasSuffix(expressionText(v.Tag), ".Fill.Shading") {
			sw = v
			return false
		}
		return true
	})
	if sw == nil {
		return nil, fmt.Errorf("cannot locate legacy shading switch")
	}
	indexed := map[int]gradientPreset{}
	for _, stmt := range sw.Body.List {
		c := stmt.(*ast.CaseClause)
		for _, expr := range c.List {
			id, err := strconv.Atoi(expressionText(expr))
			if err != nil {
				return nil, err
			}
			p := gradientPreset{stops: []float64{0, 1}}
			for _, stmt := range c.Body {
				a, ok := stmt.(*ast.AssignStmt)
				if !ok || len(a.Lhs) != 1 || len(a.Rhs) != 1 {
					return nil, fmt.Errorf("unsupported legacy gradient statement")
				}
				lhs, ok := a.Lhs[0].(*ast.SelectorExpr)
				if !ok || expressionText(lhs.X) != "gradient" {
					return nil, fmt.Errorf("unsupported legacy gradient assignment")
				}
				switch lhs.Sel.Name {
				case "Type":
					p.kind, err = stringLiteral(a.Rhs[0])
				case "Degree":
					if index, ok := a.Rhs[0].(*ast.IndexExpr); ok && expressionText(index.X) == "variants" {
						if id >= len(variants.Elts) {
							return nil, fmt.Errorf("gradient index out of range")
						}
						p.degree, err = numeric(variants.Elts[id])
					} else {
						err = setGeometry(&p, "Degree", a.Rhs[0])
					}
				default:
					err = setGeometry(&p, lhs.Sel.Name, a.Rhs[0])
				}
				if err != nil {
					return nil, err
				}
			}
			indexed[id] = p
		}
	}
	values := make([]gradientPreset, len(indexed))
	for i := range values {
		p, ok := indexed[i]
		if !ok {
			return nil, fmt.Errorf("non-contiguous gradient preset IDs")
		}
		values[i] = p
	}
	return values, nil
}
func setGeometry(p *gradientPreset, name string, value ast.Expr) error {
	n, err := numeric(value)
	if err != nil {
		return err
	}
	switch name {
	case "Degree":
		p.degree = n
	case "Left":
		p.left = n
	case "Right":
		p.right = n
	case "Top":
		p.top = n
	case "Bottom":
		p.bottom = n
	default:
		return fmt.Errorf("unknown gradient field %s", name)
	}
	return nil
}
