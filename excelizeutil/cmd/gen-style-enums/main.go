type enumSpec struct {
	typeName       string
	constantPrefix string
	packageVar     string
	legacyFunction string
	legacyVariable string
}

var sourceDir = flag.String("source", "", "Excelize source directory (default: selected module)")
var checkOutput = flag.Bool("check", false, "fail if generated files need updating")

func main() {
	flag.Parse()
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	moduleDir := *sourceDir
	var err error
	if moduleDir == "" {
		moduleDir, err = excelizeModuleDir()
	}
	if err != nil {
		return err
	}
	public, private, err := generatedSources(moduleDir)
	if err != nil {
		return err
	}
	if err := saveGenerated("../excelizestyle/style_enums_gen.go", public); err != nil {
		return err
	}
	return saveGenerated("style_enums_gen.go", private)
}

func generatedSources(moduleDir string) ([]byte, []byte, error) {
	filename := filepath.Join(moduleDir, "styles.go")
	file, err := parser.ParseFile(token.NewFileSet(), filename, nil, parser.AllErrors|parser.ParseComments)
	if err != nil {
		return nil, nil, fmt.Errorf("parse Excelize styles.go: %w", err)
	}

	specs := []enumSpec{
		{
			typeName:       "fillPattern",
			constantPrefix: "fillPattern",
			packageVar:     "styleFillPatterns",
			legacyFunction: "newFills",
			legacyVariable: "patterns",
		},
		{
			typeName:       "borderStyle",
			constantPrefix: "borderStyle",
			packageVar:     "styleBorders",
			legacyFunction: "newBorders",
			legacyVariable: "styles",
		},
	}

	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage excelizeutil\n\nimport \"github.com/tomtwinkle/excelizeam/excelizestyle\"\n\n")
	for _, spec := range specs {
		publicName, err := enumIdentifier(spec.typeName)
		if err != nil {
			return nil, nil, err
		}
		fmt.Fprintf(&output, "type %s = excelizestyle.%s\nconst %sNone = excelizestyle.%sNone\nfunc parse%s(value string) (%s,bool) { return excelizestyle.Parse%s(value) }\n\n", spec.typeName, publicName, spec.typeName, publicName, publicName, spec.typeName, publicName)
	}

	public, geometry, err := additionalEnums(moduleDir, file, specs)
	if err != nil {
		return nil, nil, err
	}
	output.Write(geometry)
	public, err = format.Source(public)
	if err != nil {
		return nil, nil, fmt.Errorf("format public enums: %w", err)
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("format generated enums: %w", err)
	}
	return public, formatted, nil
}

func excelizeModuleDir() (string, error) {
	const modulePath = "github.com/xuri/excelize/v2"
	download := exec.Command("go", "mod", "download", modulePath)
	if output, err := download.CombinedOutput(); err != nil {
		return "", fmt.Errorf("download Excelize module: %w: %s", err, strings.TrimSpace(string(output)))
	}
	command := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", modulePath)
	output, err := command.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("locate Excelize module: %w: %s", err, strings.TrimSpace(string(output)))
	}
	dir := strings.TrimSpace(string(output))
	if dir == "" {
		return "", fmt.Errorf("locate Excelize module: go list returned an empty directory")
	}
	return dir, nil
}

func findEnumValues(file *ast.File, spec enumSpec) ([]string, error) {
	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok || group.Tok != token.VAR {
			continue
		}
		for _, rawSpec := range group.Specs {
			valueSpec, ok := rawSpec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, name := range valueSpec.Names {
				if name.Name != spec.packageVar {
					continue
				}
				if i >= len(valueSpec.Values) {
					return nil, fmt.Errorf("Excelize styles.go: %s has no initializer", spec.packageVar)
				}
				return stringValues(valueSpec.Values[i], spec.packageVar)
			}
		}
	}

	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Name.Name != spec.legacyFunction || function.Body == nil {
			continue
		}
		var values []string
		var found bool
		var foundErr error
		ast.Inspect(function.Body, func(node ast.Node) bool {
			assignment, ok := node.(*ast.AssignStmt)
			if !ok {
				return true
			}
			for i, left := range assignment.Lhs {
				name, ok := left.(*ast.Ident)
				if !ok || name.Name != spec.legacyVariable || i >= len(assignment.Rhs) {
					continue
				}
				values, foundErr = stringValues(assignment.Rhs[i], spec.legacyVariable)
				found = foundErr == nil
				return false
			}
			return true
		})
		if foundErr != nil {
			return nil, foundErr
		}
		if found {
			return values, nil
		}
		break
	}

	return nil, fmt.Errorf(
		"Excelize styles.go: could not find %s (expected package variable %s or %s.%s)",
		spec.typeName, spec.packageVar, spec.legacyFunction, spec.legacyVariable,
	)
}

func stringValues(expression ast.Expr, label string) ([]string, error) {
	literal, ok := expression.(*ast.CompositeLit)
	if !ok {
		return nil, fmt.Errorf("Excelize styles.go: %s is not a composite literal", label)
	}
	array, ok := literal.Type.(*ast.ArrayType)
	if !ok {
		return nil, fmt.Errorf("Excelize styles.go: %s is not a slice or array", label)
	}
	identifier, ok := array.Elt.(*ast.Ident)
	if !ok || identifier.Name != "string" {
		return nil, fmt.Errorf("Excelize styles.go: %s is not a string slice", label)
	}
	values := make([]string, 0, len(literal.Elts))
	for _, element := range literal.Elts {
		basic, ok := element.(*ast.BasicLit)
		if !ok || basic.Kind != token.STRING {
			return nil, fmt.Errorf("Excelize styles.go: %s contains a non-string value", label)
		}
		value, err := strconv.Unquote(basic.Value)
		if err != nil {
			return nil, fmt.Errorf("Excelize styles.go: decode %s value: %w", label, err)
		}
		values = append(values, value)
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("Excelize styles.go: %s is empty", label)
	}
	return values, nil
}

func writeEnum(output *bytes.Buffer, spec enumSpec, values []string) error {
	identifiers := make([]string, len(values))
	seenValues := make(map[string]struct{}, len(values))
	seenIdentifiers := make(map[string]struct{}, len(values))
	for i, value := range values {
		if _, exists := seenValues[value]; exists {
			return fmt.Errorf("Excelize styles.go: %s contains duplicate value %q", spec.typeName, value)
		}
		seenValues[value] = struct{}{}
		name, err := enumIdentifier(value)
		if err != nil {
			return fmt.Errorf("Excelize styles.go: invalid %s value %q: %w", spec.typeName, value, err)
		}
		if _, exists := seenIdentifiers[name]; exists {
			return fmt.Errorf("Excelize styles.go: %s values produce duplicate enum %s", spec.typeName, name)
		}
		seenIdentifiers[name] = struct{}{}
		identifiers[i] = name
	}

	fmt.Fprintf(output, "type %s int\n\nconst (\n", spec.typeName)
	for i, identifier := range identifiers {
		if i == 0 {
			fmt.Fprintf(output, "\t%s%s %s = iota\n", spec.constantPrefix, identifier, spec.typeName)
		} else {
			fmt.Fprintf(output, "\t%s%s\n", spec.constantPrefix, identifier)
		}
	}
	fmt.Fprintf(output, "\t%sCount\n)\n\n", spec.typeName)

	fmt.Fprintf(output, "func (value %s) String() string {\n\tswitch value {\n", spec.typeName)
	for i, identifier := range identifiers {
		fmt.Fprintf(output, "\tcase %s%s:\n\t\treturn %s\n", spec.constantPrefix, identifier, strconv.Quote(values[i]))
	}
	fmt.Fprintf(output, "\tdefault:\n\t\treturn \"\"\n\t}\n}\n\n")

	typeName, err := enumIdentifier(spec.typeName)
	if err != nil {
		return err
	}
	parsePrefix := "parse"
	if unicode.IsUpper([]rune(spec.typeName)[0]) {
		parsePrefix = "Parse"
	}
	fmt.Fprintf(output, "func %s%s(value string) (%s, bool) {\n\tswitch value {\n", parsePrefix, typeName, spec.typeName)
	for i, identifier := range identifiers {
		fmt.Fprintf(output, "\tcase %s:\n\t\treturn %s%s, true\n", strconv.Quote(values[i]), spec.constantPrefix, identifier)
	}
	fmt.Fprintf(output, "\tdefault:\n\t\treturn 0, false\n\t}\n}\n\n")
	return nil
}

func enumIdentifier(value string) (string, error) {
	runes := []rune(value)
	if len(runes) == 0 {
		return "", fmt.Errorf("empty value")
	}
	for _, character := range runes {
		if !unicode.IsLetter(character) && !unicode.IsDigit(character) && character != '_' {
			return "", fmt.Errorf("unsupported character %q", character)
		}
	}
	if !unicode.IsLetter(runes[0]) && runes[0] != '_' {
		return "", fmt.Errorf("identifier must start with a letter or underscore")
	}
	runes[0] = unicode.ToUpper(runes[0])
	name := string(runes)
	return name, nil
}
